<script>
    /* =========================================================
   EEARTH WATER PRODUCT SLIDER
========================================================= */

document.addEventListener("DOMContentLoaded", function () {

    const products = [

        {
            size: "200",
            unit: "ml",
            subtitle: "COMPACT",

            description:
                "Perfect for quick refreshment and compact servings. The eearth 200 ml bottle is designed for convenience, making it easy to carry wherever you go.",

            image:
                "images/200m.png"
        },


        {
            size: "250",
            unit: "ml",
            subtitle: "EVERYDAY",

            description:
                "A convenient everyday size made for quick hydration. The eearth 250 ml bottle brings pure water to your daily moments.",

            image:
                "images/250.png"
        },


        {
            size: "500",
            unit: "ml",
            subtitle: "ESSENTIAL",

            description:
                "The perfect balance between portability and hydration. eearth 500 ml is made for work, travel, events and everyday life.",

            image:
                "images/500ml-.png"
        },


       


        {
            size: "1",
            unit: "L",
            subtitle: "COMPLETE",

            description:
                "Made for longer hydration and shared moments. The eearth 1 litre bottle delivers pure mineral water in a premium format.",

            image:
                "images/1ltr-.png"
        }

    ];


    /* =====================================================
       ELEMENTS
    ===================================================== */

    const sizeNumber =
        document.getElementById("waterSizeNumber");

    const sizeUnit =
        document.getElementById("waterSizeUnit");

    const subtitle =
        document.getElementById("waterSubtitle");

    const description =
        document.getElementById("waterDescription");

    const productImage =
        document.getElementById("mainProductImage");

    const currentProduct =
        document.getElementById("currentProduct");

    const totalProducts =
        document.getElementById("totalProducts");

    const previousButton =
        document.getElementById("prevProduct");

    const nextButton =
        document.getElementById("nextProduct");

    const thumbnails =
        document.querySelectorAll(".ee-product-thumb");

    const bottle =
        document.getElementById("mainBottle");


    /* =====================================================
       CURRENT SLIDE
    ===================================================== */

    let currentIndex = 0;

    totalProducts.textContent =
        String(products.length).padStart(2, "0");


    /* =====================================================
       UPDATE SLIDE
    ===================================================== */

    function updateProduct(index, direction = 1) {

        const product =
            products[index];


        /* Remove animation */

        bottle.classList.remove(
            "ee-bottle-slide-next",
            "ee-bottle-slide-prev"
        );


        /* Force browser reflow */

        void bottle.offsetWidth;


        /* Add direction animation */

        if (direction === 1) {

            bottle.classList.add(
                "ee-bottle-slide-next"
            );

        } else {

            bottle.classList.add(
                "ee-bottle-slide-prev"
            );

        }


        /* Update text */

        sizeNumber.textContent =
            product.size;

        sizeUnit.textContent =
            product.unit;

        subtitle.textContent =
            product.subtitle;

        description.textContent =
            product.description;


        /* Update image */

        productImage.src =
            product.image;

        productImage.alt =
            `eearth ${product.size} ${product.unit} Natural Mineral Water`;


        /* Update counter */

        currentProduct.textContent =
            String(index + 1).padStart(2, "0");


        /* Update active thumbnail */

        thumbnails.forEach(function (thumb, i) {

            thumb.classList.toggle(
                "active",
                i === index
            );

        });


        currentIndex = index;

    }


    /* =====================================================
       NEXT
    ===================================================== */

    function nextProduct() {

        let nextIndex =
            currentIndex + 1;

        if (nextIndex >= products.length) {

            nextIndex = 0;

        }

        updateProduct(
            nextIndex,
            1
        );

    }


    /* =====================================================
       PREVIOUS
    ===================================================== */

    function previousProduct() {

        let previousIndex =
            currentIndex - 1;

        if (previousIndex < 0) {

            previousIndex =
                products.length - 1;

        }

        updateProduct(
            previousIndex,
            -1
        );

    }


    /* =====================================================
       BUTTON EVENTS
    ===================================================== */

    nextButton.addEventListener(
        "click",
        nextProduct
    );


    previousButton.addEventListener(
        "click",
        previousProduct
    );


    /* =====================================================
       THUMBNAIL EVENTS
    ===================================================== */

    thumbnails.forEach(function (thumbnail) {

        thumbnail.addEventListener(
            "click",
            function () {

                const selectedIndex =
                    parseInt(
                        this.dataset.index,
                        10
                    );


                if (
                    selectedIndex ===
                    currentIndex
                ) {
                    return;
                }


                const direction =
                    selectedIndex >
                    currentIndex
                        ? 1
                        : -1;


                updateProduct(
                    selectedIndex,
                    direction
                );

            }
        );

    });


    /* =====================================================
       KEYBOARD SUPPORT
    ===================================================== */

    document.addEventListener(
        "keydown",
        function (event) {

            /*
             Only activate when
             Water section is visible.
            */

            const waterSection =
                document.getElementById("water");

            if (!waterSection) {
                return;
            }


            const rect =
                waterSection.getBoundingClientRect();


            const isVisible =
                rect.top <
                window.innerHeight &&
                rect.bottom > 0;


            if (!isVisible) {
                return;
            }


            if (event.key === "ArrowRight") {

                nextProduct();

            }


            if (event.key === "ArrowLeft") {

                previousProduct();

            }

        }
    );


    /* =====================================================
       TOUCH / SWIPE SUPPORT
    ===================================================== */

    let touchStartX = 0;

    let touchEndX = 0;


    const productArea =
        document.querySelector(
            ".ee-water-product-area"
        );


    productArea.addEventListener(
        "touchstart",
        function (event) {

            touchStartX =
                event.changedTouches[0].screenX;

        },
        {
            passive: true
        }
    );


    productArea.addEventListener(
        "touchend",
        function (event) {

            touchEndX =
                event.changedTouches[0].screenX;

            handleSwipe();

        },
        {
            passive: true
        }
    );


    function handleSwipe() {

        const difference =
            touchStartX - touchEndX;


        /*
         Ignore very small movement
        */

        if (
            Math.abs(difference) <
            50
        ) {

            return;

        }


        if (difference > 0) {

            nextProduct();

        } else {

            previousProduct();

        }

    }


    /* =====================================================
       INITIALIZE
    ===================================================== */

    updateProduct(
        0,
        1
    );

});
    </script>
